const GOOGLE_LETTERS = ["#4285F4", "#EA4335", "#FBBC05", "#4285F4", "#34A853", "#EA4335"];
const GEMINI_GRADIENT = "linear-gradient(90deg, #4796e3 0%, #9177c7 50%, #ca6673 100%)";

/** The name, letter by letter (so each can rise in on its own), styled per brand. */
export function BrandName({ brand, name }: { brand: Brand; name: string }) {
  const chars = Array.from(name);
  const googleWord = brand === "google" || brand === "maps" || brand === "aimode";

  return (
    <span
      className={cn(
        "inline-flex",
        brand === "chatgpt" && "font-semibold tracking-[-0.03em] text-white",
        googleWord && "font-medium tracking-[-0.02em] text-white/80",
        brand === "gemini" && "font-medium tracking-[-0.02em]",
        brand === "claude" && "font-serif font-medium tracking-[-0.02em] text-white",
        brand === "perplexity" && "font-medium tracking-[-0.03em] text-white",
      )}
    >
      {chars.map((ch, i) => {
        const style: CSSProperties & { "--i": number } = { "--i": i };
        if (googleWord && i < GOOGLE_LETTERS.length) style.color = GOOGLE_LETTERS[i];
        if (brand === "gemini") {
          style.backgroundImage = GEMINI_GRADIENT;
          style.backgroundSize = "600% 100%";
          style.backgroundPosition = `${(i / Math.max(chars.length - 1, 1)) * 100}% 0`;
        }
        return (
          <span
            key={i}
            className={cn("rot-ch inline-block", brand === "gemini" && "bg-clip-text text-transparent")}
            style={style}
          >
            {ch === " " ? " " : ch}
          </span>
        );
      })}
    </span>
  );
}

